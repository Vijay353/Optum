/**
 * Generates the downloadable sample workbook, per-entity CSVs, invalid-data
 * example workbooks and the generated schema reference.
 * Usage: npm run template
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import ExcelJS from "exceljs";
import { loadFixtureDataset } from "../src/data/datasetStore";
import { buildWorkbook, datasetToRows, toCsv } from "../src/data/workbook";
import { WORKBOOK_SHEETS, LIMITS } from "../src/data/workbookSchema";
import { DATASET_SCHEMA_VERSION } from "../src/data/dataset";

const OUT = "data/templates";
mkdirSync(join(OUT, "csv"), { recursive: true });
mkdirSync(join(OUT, "invalid"), { recursive: true });

const { dataset, issues } = loadFixtureDataset("fixtures/base");
if (issues.length) throw new Error(`base fixtures invalid: ${JSON.stringify(issues)}`);

async function mutate(name: string, fn: (wb: ExcelJS.Workbook) => void, note: string) {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.load((await buildWorkbook(dataset, { title: `INVALID EXAMPLE — ${note}` })) as unknown as ArrayBuffer);
  fn(wb);
  writeFileSync(join(OUT, "invalid", name), Buffer.from(await wb.xlsx.writeBuffer()));
  return `| \`invalid/${name}\` | ${note} |`;
}
const cellOf = (wb: ExcelJS.Workbook, sheet: string, col: string, row: number) => {
  const ws = wb.getWorksheet(sheet)!;
  let idx = 0;
  ws.getRow(1).eachCell((c, i) => { if (c.value === col) idx = i; });
  return ws.getRow(row).getCell(idx);
};

const main = async () => {
  writeFileSync(join(OUT, "evidencebridge-template.xlsx"), await buildWorkbook(dataset, { title: "EvidenceBridge synthetic simulator workbook (template)" }));
  for (const s of WORKBOOK_SHEETS) {
    writeFileSync(join(OUT, "csv", `${s.sheet}.csv`), toCsv(datasetToRows(dataset, s.sheet), s.columns.map((c) => c.name)));
  }
  const rows = [
    await mutate("missing-sheet.xlsx", (wb) => wb.removeWorksheet(wb.getWorksheet("coverage")!.id), "coverage sheet removed (fails in replace mode)"),
    await mutate("wrong-types.xlsx", (wb) => { cellOf(wb, "prior_auth_drafts", "version", 2).value = "three"; cellOf(wb, "provider_attribution", "attributed", 2).value = "maybe"; }, "non-integer version, non-boolean attributed"),
    await mutate("duplicate-ids.xlsx", (wb) => { cellOf(wb, "patients", "id", 3).value = "SYN-PAT-1042"; }, "duplicate patient primary key"),
    await mutate("orphan-reference.xlsx", (wb) => { cellOf(wb, "coverage", "patientId", 2).value = "SYN-PAT-9999"; }, "coverage points at a patient that does not exist (cascades to dependents)"),
    await mutate("invalid-status.xlsx", (wb) => { cellOf(wb, "prior_auth_drafts", "businessStatus", 2).value = "EVIDENCE_REVIEW_PENDING"; }, "system-managed status supplied by import"),
    await mutate("formula-cell.xlsx", (wb) => { cellOf(wb, "patients", "ageBand", 2).value = { formula: "HYPERLINK(\"http://example.invalid\",\"55-64\")", result: "55-64" } as ExcelJS.CellFormulaValue; }, "formula cell (never evaluated; rejected)"),
    await mutate("stale-revision.xlsx", (wb) => { cellOf(wb, "prior_auth_drafts", "version", 2).value = 1; }, "draft PA-DRAFT-99412 at v1 while the simulator holds v3"),
    await mutate("real-identifier.xlsx", (wb) => { cellOf(wb, "coverage", "planName", 2).value = "Plan for member 123-45-6789"; cellOf(wb, "patients", "id", 2).value = "MRN-0042"; }, "SSN-like text and a non-synthetic patient id"),
  ];
  const schema: string[] = [
    `# Workbook schema reference — ${DATASET_SCHEMA_VERSION}`,
    "",
    "Generated by `npm run template` from `src/data/workbookSchema.ts`. Do not edit by hand.",
    "",
    `Limits: ${LIMITS.maxBytes / 1048576} MB per file, ${LIMITS.maxRowsPerSheet} rows per sheet, ${LIMITS.maxColumns} columns per sheet. Formats: .xlsx (preferred) or one \`<entity>.csv\` per entity (merge mode only).`,
    "",
  ];
  for (const s of WORKBOOK_SHEETS) {
    schema.push(`## ${s.sheet}`, "", `${s.description}  `, `Owner: ${s.owner} · Primary key: \`${s.primaryKey}\``, "", "| Column | Type | Required | Editable | Allowed | Description |", "|---|---|---|---|---|---|");
    for (const c of s.columns) schema.push(`| \`${c.name}\` | ${c.type}${c.nullable ? " (nullable)" : ""} | ${c.required ? "yes" : "no"} | ${c.editable ? "yes" : "system"} | ${(c.allowed ?? []).join(", ")} | ${c.description} |`);
    schema.push("");
  }
  schema.push("## Invalid-data examples", "", "| File | What is wrong |", "|---|---|", ...rows, "");
  writeFileSync(join(OUT, "SCHEMA.md"), schema.join("\n"));
  console.log(`Wrote ${OUT}/evidencebridge-template.xlsx, ${WORKBOOK_SHEETS.length} CSVs, ${rows.length} invalid examples and SCHEMA.md`);
};
main();
